
package id.vortexconverter.converter;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.UUID;

public final class BedrockResourcePackBuilder {

    private final Gson gson = new GsonBuilder()
            .setPrettyPrinting()
            .create();

    public BuildResult build(
            BlockbenchConversionService.ConversionResult conversion,
            File outputDirectory,
            String packName
    ) throws IOException {

        if (conversion == null) {
            throw new IOException("Conversion result cannot be null.");
        }

        if (conversion.geometryFile() == null
                || !conversion.geometryFile().isFile()) {
            throw new IOException("Geometry file does not exist.");
        }

        if (outputDirectory == null) {
            throw new IOException("Output directory cannot be null.");
        }

        String safeName = sanitize(packName);

        Path packRoot = outputDirectory.toPath()
                .resolve(safeName);

        Files.createDirectories(packRoot);

        createDirectories(packRoot);

        JsonObject manifest = createManifest(
                packName,
                UUID.randomUUID(),
                UUID.randomUUID()
        );

        writeJson(
                packRoot.resolve("manifest.json"),
                manifest
        );

        Path geometryDestination = packRoot
                .resolve("models")
                .resolve("entity")
                .resolve("geometry.geo.json");

        copyFile(
                conversion.geometryFile().toPath(),
                geometryDestination
        );

        int copiedAnimations = 0;

        if (conversion.animationFiles() != null) {
            for (File animation : conversion.animationFiles()) {
                if (animation == null || !animation.isFile()) {
                    continue;
                }

                String fileName = animation.getName();

                Path destination = packRoot
                        .resolve("animations")
                        .resolve(fileName);

                copyFile(animation.toPath(), destination);
                copiedAnimations++;
            }
        }

        return new BuildResult(
                packRoot.toFile(),
                packRoot.resolve("manifest.json").toFile(),
                geometryDestination.toFile(),
                copiedAnimations
        );
    }

    private void createDirectories(Path root) throws IOException {
        Files.createDirectories(
                root.resolve("models").resolve("entity")
        );

        Files.createDirectories(
                root.resolve("animations")
        );

        Files.createDirectories(
                root.resolve("textures").resolve("entity")
        );

        Files.createDirectories(
                root.resolve("texts")
        );
    }

    private JsonObject createManifest(
            String packName,
            UUID headerUuid,
            UUID moduleUuid
    ) {
        JsonObject manifest = new JsonObject();

        manifest.addProperty("format_version", 2);

        JsonObject header = new JsonObject();

        header.addProperty(
                "name",
                packName == null || packName.isBlank()
                        ? "Vortex Bedrock Pack"
                        : packName
        );

        header.addProperty(
                "description",
                "Generated by VortexConverter"
        );

        header.addProperty("uuid", headerUuid.toString());
        header.addProperty("version", "1.0.0");

        JsonArray minimumEngineVersion = new JsonArray();
        minimumEngineVersion.add(1);
        minimumEngineVersion.add(20);
        minimumEngineVersion.add(0);

        header.add(
                "min_engine_version",
                minimumEngineVersion
        );

        manifest.add("header", header);

        JsonObject module = new JsonObject();

        module.addProperty("type", "resources");
        module.addProperty("uuid", moduleUuid.toString());
        module.addProperty("version", "1.0.0");
        module.addProperty(
                "description",
                "VortexConverter generated resource module"
        );

        JsonArray modules = new JsonArray();
        modules.add(module);

        manifest.add("modules", modules);

        return manifest;
    }

    private void copyFile(
            Path source,
            Path destination
    ) throws IOException {

        if (source == null || !Files.isRegularFile(source)) {
            throw new IOException(
                    "Source file does not exist: " + source
            );
        }

        Path parent = destination.getParent();

        if (parent != null) {
            Files.createDirectories(parent);
        }

        Files.copy(
                source,
                destination,
                StandardCopyOption.REPLACE_EXISTING
        );
    }

    private void writeJson(
            Path destination,
            JsonObject json
    ) throws IOException {

        Path parent = destination.getParent();

        if (parent != null) {
            Files.createDirectories(parent);
        }

        try (var writer = Files.newBufferedWriter(
                destination,
                StandardCharsets.UTF_8
        )) {
            gson.toJson(json, writer);
        }
    }

    private String sanitize(String value) {
        if (value == null || value.isBlank()) {
            return "VortexPack";
        }

        String result = value
                .replaceAll("[^a-zA-Z0-9_-]", "_");

        return result.isBlank() ? "VortexPack" : result;
    }

    public record BuildResult(
            File packDirectory,
            File manifestFile,
            File geometryFile,
            int animationCount
    ) {}
}
